// Working principle of Queue

// Answer:
// A Queue is a linear data structure that follows the FIFO (First In, First Out) principle.
// The element that is inserted first is removed first.

// In Queue:

// Insertion is done from the Rear end

// Deletion is done from the Front end

// Queue is mainly used where order of execution is important.