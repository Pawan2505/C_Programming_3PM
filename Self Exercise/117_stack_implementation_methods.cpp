// 📝 This question explains:

// Different ways to implement Stack

// Answer:

// Using Array
// Stack is implemented using a fixed-size array.
// Fast access but size is limited.

// Using Linked List
// Each node represents a stack element.
// Dynamic size, no overflow until memory is full.

// Using Vector (C++)
// Stack is implemented using vector with push_back() and pop_back().
// Dynamic and easy to use.