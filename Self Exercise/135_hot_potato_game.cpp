// 📝 This question explains:

// Hot Potato Game concept

// Use of Queue data structure

// Answer:
// The Hot Potato Game is a popular game used to explain the Queue data structure.

// Concept:

// Players stand in a circle

// Music plays and a “hot potato” is passed

// When music stops, the person holding the potato is eliminated

// Queue Explanation:

// Players are stored in a queue

// The front player is removed and added to the rear

// After a fixed number of passes, one player is removed

// Process continues until one winner remains

// Why Queue is used:

// Maintains order

// Follows FIFO principle